export const normalize = (value) =>
  String(value ?? "")
    .toUpperCase()
    .replace(/Ё/g, "Е");
export const words = groups.flatMap(([difficulty, theme, text]) =>
  text
    .trim()
    .split("\n")
    .map((line) => {
      const [display, clue] = line.split("|");
      const answer = normalize(display);
      return {
        id: answer.toLowerCase(),
        answer,
        display,
        clue,
        theme,
        difficulty,
        length: answer.length,
      };
    }),
);
export const wordById = new Map(words.map((word) => [word.id, word]));
